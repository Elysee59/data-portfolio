def setup(title: str, icon: str = "📊") -> None:
    st.set_page_config(page_title=f"{title} · Elysée Mugabire", page_icon=icon, layout="wide")
    st.markdown(CSS, unsafe_allow_html=True)
    with st.sidebar:
        st.markdown("### Elysée Mugabire")
        st.caption("Data Scientist & BI Engineer")
        st.markdown(
            "[GitHub repository](https://github.com/Elysee59/data-portfolio)  \n"
            "[LinkedIn](https://www.linkedin.com/in/elysee-mugabire/)"
        )
        st.divider()
        st.caption("All data in this app is synthetic and generated by the project code.")


def hero(title: str, subtitle: str, pills: list[str] | None = None) -> None:
    pills_html = "".join(f'<span class="pill">{p}</span>' for p in (pills or []))
    st.markdown(f'<div class="hero"><h1>{title}</h1><p>{subtitle}</p>{pills_html}</div>', unsafe_allow_html=True)


def insight(text: str) -> None:
    st.markdown(f'<div class="insight">{text}</div>', unsafe_allow_html=True)


def kv(label: str, value: str) -> str:
    """Small key/value card that never truncates long values (unlike st.metric)."""
    return f'<div class="kv"><div class="k">{label}</div><div class="v">{value}</div></div>'


def chips(items: list[str]) -> None:
    st.markdown("".join(f'<span class="chip">{i}</span>' for i in items), unsafe_allow_html=True)
